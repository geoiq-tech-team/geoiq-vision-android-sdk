// Baseline profile — generated by :baselineprofile driving the sample app through a session.
// Regenerate: ./gradlew :GEOIQ-ANDROID-LK-VISION-BOT-SDK:generateBaselineProfile
// Output lands in src/main/generated/baselineProfiles/ and is packaged into the AAR.
baselineProfile {
    mergeIntoMain = true
    // Generation needs a device and the staging server; never run it as part of a normal build.
    automaticGenerationDuringBuild = false
    filter {
        // `.*` = this package only (incl. inner classes), so the sample app in `.sample` is excluded.
        // Filter rules can't match class-name prefixes — keep the sample out of this package.
        include("com.geoiq.geoiq_android_lk_vision_bot_sdk.*")
        // LiveKit ships no profile of its own; its Kotlin/WebRTC Java code is on the hot path.
        include("io.livekit.android.**")
        include("livekit.org.webrtc.**")
    }
}

dependencies {
    // No AndroidX/Material deps of our own: the SDK uses none of them, and pinning newer
